// Wire format of the public checkout (design 10.1 to 10.3, ADR 0033): the event page's data,
// placing an order and polling it. Buyers have no account: the order's access token is
// their only credential, sent as a bearer token, never in a URL.

import { z } from "zod";

const isoTime = z.iso.datetime({ offset: true });

/** Lowercase words joined by hyphens, as events.events.slug. */
export const EVENT_SLUG_PATTERN = /^[a-z0-9]+(-[a-z0-9]+)*$/;
export const eventSlug = z.string().min(3).max(80).regex(EVENT_SLUG_PATTERN);

/** Header carrying the browser's idempotency key on POST /v1/orders. */
export const IDEMPOTENCY_HEADER = "Idempotency-Key";
/** At least 128 random bits, generated by the browser, in base64url or hex. */
export const idempotencyKey = z.string().regex(/^[A-Za-z0-9_-]{22,128}$/);

/** Prefix of an order's access token. */
export const ORDER_TOKEN_PREFIX = "pro_";

export const AVAILABILITY_LEVELS = ["available", "few", "sold_out"] as const;
export type AvailabilityLevel = (typeof AVAILABILITY_LEVELS)[number];

export const AGE_RATINGS = ["all", "12plus", "18plus"] as const;

export const publicTicketType = z.object({
  id: z.uuid(),
  name: z.string(),
  zone: z.string().nullable(),
  priceCrc: z.int().nonnegative(),
  /** The service charge with its tax, per ticket, shown itemized before paying (10.5). */
  serviceChargeCrc: z.int().nonnegative(),
  availability: z.enum(AVAILABILITY_LEVELS),
});
export type PublicTicketType = z.infer<typeof publicTicketType>;

/** GET /v1/events/:slug: an event on sale, as a buyer may see it. */
export const publicEvent = z.object({
  event: z.object({
    id: z.uuid(),
    slug: eventSlug,
    name: z.string(),
    venueName: z.string(),
    startsAt: isoTime,
    endsAt: isoTime,
    ageRating: z.enum(AGE_RATINGS),
  }),
  ticketTypes: z.array(publicTicketType),
  /** The versions of the documents the buyer accepts by paying (14.3, 14.4). */
  legal: z.object({ termsVersion: z.string(), privacyVersion: z.string() }),
});
export type PublicEvent = z.infer<typeof publicEvent>;

/** An email address or a phone number, typed in one field (10.1). */
export type BuyerContact = { readonly email: string } | { readonly phone: string };

const emailSchema = z.email().max(254);

/**
 * Reads the single contact field: an address when it has an "@", otherwise a phone number
 * of 8 to 15 digits (spaces, dashes, dots and parentheses ignored). Eight digits are a
 * Costa Rican number and get +506.
 */
export const buyerContact = z
  .string()
  .trim()
  .min(1)
  .max(254)
  .transform((text, ctx): BuyerContact => {
    if (text.includes("@")) {
      const email = emailSchema.safeParse(text.toLowerCase());
      if (email.success) return { email: email.data };
    } else {
      const digits = text.replace(/[\s().-]/g, "");
      if (/^[0-9]{8}$/.test(digits)) return { phone: `+506${digits}` };
      if (/^\+[0-9]{8,15}$/.test(digits)) return { phone: digits };
    }
    ctx.addIssue({ code: "custom", message: "an email address or a phone number" });
    return z.NEVER;
  });

/** POST /v1/orders, with the Idempotency-Key header. */
export const createOrderRequest = z.object({
  eventId: z.uuid(),
  ticketTypeId: z.uuid(),
  /** A sanity bound for the field, not the per-order limit of 9.3 (Phase 6). */
  quantity: z.int().min(1).max(100),
  contact: buyerContact,
  /** The versions the buyer saw next to the pay button; they must still be current. */
  termsVersion: z.string().min(1).max(32),
  privacyVersion: z.string().min(1).max(32),
  /** The optional, unchecked-by-default box for commercial messages (14.3). */
  marketing: z.boolean().default(false),
});
export type CreateOrderRequest = z.input<typeof createOrderRequest>;

export const ORDER_STATUSES = ["pending", "paid", "expired", "refund_due", "refunded"] as const;
export type OrderStatus = (typeof ORDER_STATUSES)[number];

/** What the payment screen needs: the exact data to pay by SINPE (10.2). */
export const placedOrder = z.object({
  /** The access token: kept by the wallet, sent as `Authorization: Bearer`. */
  token: z.string().startsWith(ORDER_TOKEN_PREFIX),
  /** The code to write in the SINPE description. */
  orderCode: z.string(),
  status: z.enum(ORDER_STATUSES),
  amountCrc: z.int().nonnegative(),
  /** Whether no other pending order has this amount (ADR 0031). */
  amountUnique: z.boolean(),
  /** The platform's SINPE Móvil number, from configuration. */
  sinpeNumber: z.string(),
  expiresAt: isoTime,
});
export type PlacedOrder = z.infer<typeof placedOrder>;

/** GET /v1/orders/current: the state the payment screen polls. */
export const orderState = z.object({
  orderCode: z.string(),
  status: z.enum(ORDER_STATUSES),
  amountCrc: z.int().nonnegative(),
  expiresAt: isoTime,
  paidAt: isoTime.nullable(),
});
export type OrderState = z.infer<typeof orderState>;
