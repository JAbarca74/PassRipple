-- The ticket: one record per entry, whatever its origin (sale, complimentary or door
-- sale: never a parallel path). This first version holds what redemption needs. Device
-- binding arrives with the credentials (Phase 1), and named attendees, whose documents
-- must be encrypted at rest, arrive in Phase 7.
--
-- A ticket has no "redeemed" status: whether it was used is recorded by redemption,
-- which owns invariant I1 (ADR 0012).

CREATE TABLE ticketing.tickets (
  id             uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
  event_id       uuid        NOT NULL REFERENCES events.events (id),
  ticket_type_id uuid        NOT NULL REFERENCES catalog.ticket_types (id),
  -- The order a sold ticket came from. No foreign key: orders is a higher module.
  order_id       uuid,
  origin         text        NOT NULL CHECK (origin IN ('sale', 'courtesy', 'door_sale')),
  -- The door-sale block a pre-issued ticket belongs to.
  block_id       uuid,
  -- Static fallback code (Crockford Base32 with a check digit), generated by crypto.
  code_human     text        NOT NULL UNIQUE CHECK (code_human ~ '^[0-9A-HJKMNP-TV-Z]{6,20}$'),
  -- Ed25519 public key of the buyer's device, once bound.
  holder_pubkey  bytea       CHECK (length(holder_pubkey) = 32),
  key_version    smallint    NOT NULL DEFAULT 0 CHECK (key_version >= 0),
  -- Copied from the ticket type when the ticket is issued, and never changed.
  entry_mode     text        NOT NULL CHECK (entry_mode IN ('single_use', 'multi_scan')),
  status         text        NOT NULL DEFAULT 'issued' CHECK (status IN ('unsold', 'issued', 'bound', 'void')),
  created_at     timestamptz NOT NULL DEFAULT now(),
  CHECK (origin <> 'sale' OR order_id IS NOT NULL),
  CHECK (status <> 'bound' OR holder_pubkey IS NOT NULL)
);
CREATE INDEX tickets_event_idx ON ticketing.tickets (event_id);
CREATE INDEX tickets_order_idx ON ticketing.tickets (order_id) WHERE order_id IS NOT NULL;

-- A ticket takes its entry mode from its type, and the type must belong to its event.
-- Whatever entry mode the caller passes is ignored, so a public ticket can never be
-- issued as multi-scan.
CREATE FUNCTION ticketing.derive_ticket()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = pg_catalog
AS $$
DECLARE
  v_event_id   uuid;
  v_entry_mode text;
BEGIN
  SELECT t.event_id, t.entry_mode INTO v_event_id, v_entry_mode
    FROM catalog.ticket_types t WHERE t.id = NEW.ticket_type_id;
  IF v_event_id IS DISTINCT FROM NEW.event_id THEN
    RAISE EXCEPTION 'ticket type % does not belong to event %', NEW.ticket_type_id, NEW.event_id
      USING ERRCODE = 'foreign_key_violation';
  END IF;
  NEW.entry_mode := v_entry_mode;
  RETURN NEW;
END
$$;

-- Only status, binding and key version change, along these transitions:
--   unsold → issued | void      issued → bound | void      bound → bound | void
CREATE FUNCTION ticketing.guard_ticket_update()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = pg_catalog
AS $$
BEGIN
  IF (NEW.id, NEW.event_id, NEW.ticket_type_id, NEW.order_id, NEW.origin, NEW.block_id,
      NEW.code_human, NEW.entry_mode, NEW.created_at)
     IS DISTINCT FROM
     (OLD.id, OLD.event_id, OLD.ticket_type_id, OLD.order_id, OLD.origin, OLD.block_id,
      OLD.code_human, OLD.entry_mode, OLD.created_at) THEN
    RAISE EXCEPTION 'ticket %: only its status and binding can change', OLD.id
      USING ERRCODE = 'restrict_violation';
  END IF;
  IF (OLD.status, NEW.status) NOT IN (('unsold', 'unsold'), ('unsold', 'issued'), ('unsold', 'void'),
                                      ('issued', 'issued'), ('issued', 'bound'), ('issued', 'void'),
                                      ('bound', 'bound'), ('bound', 'void'), ('void', 'void')) THEN
    RAISE EXCEPTION 'ticket %: % cannot become %', OLD.id, OLD.status, NEW.status
      USING ERRCODE = 'restrict_violation';
  END IF;
  IF OLD.status = 'void' AND NEW IS DISTINCT FROM OLD THEN
    RAISE EXCEPTION 'ticket % is void', OLD.id USING ERRCODE = 'restrict_violation';
  END IF;
  RETURN NEW;
END
$$;

CREATE TRIGGER tickets_derive BEFORE INSERT ON ticketing.tickets
  FOR EACH ROW EXECUTE FUNCTION ticketing.derive_ticket();
CREATE TRIGGER tickets_guard_update BEFORE UPDATE ON ticketing.tickets
  FOR EACH ROW EXECUTE FUNCTION ticketing.guard_ticket_update();
CREATE TRIGGER tickets_no_delete BEFORE DELETE ON ticketing.tickets
  FOR EACH ROW EXECUTE FUNCTION app.reject_mutation();
CREATE TRIGGER tickets_no_truncate BEFORE TRUNCATE ON ticketing.tickets
  FOR EACH STATEMENT EXECUTE FUNCTION app.reject_mutation();

