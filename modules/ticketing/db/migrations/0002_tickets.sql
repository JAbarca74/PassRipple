-- ── Functions ────────────────────────────────────────────────────────────────
-- Issues one ticket. Called by the system when an order is paid, a complimentary ticket
-- is granted or a door-sale block is assigned. The API then emits ticket.issued.
CREATE FUNCTION ticketing.issue(
  p_event_id uuid, p_ticket_type_id uuid, p_order_id uuid, p_origin text, p_code_human text
) RETURNS uuid
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog
AS $$
DECLARE
  v_ticket_id uuid;
BEGIN
  IF app.actor_role() IS DISTINCT FROM 'system' THEN
    RAISE EXCEPTION 'only the system issues tickets' USING ERRCODE = 'insufficient_privilege';
  END IF;
  INSERT INTO ticketing.tickets (event_id, ticket_type_id, order_id, origin, code_human, entry_mode)
  VALUES (p_event_id, p_ticket_type_id, p_order_id, p_origin, p_code_human, 'single_use')
  RETURNING id INTO v_ticket_id;
  RETURN v_ticket_id;
END
$$;

-- Voids a ticket. Online only, by an organizer of the event's organization or an
-- administrator. The API then emits ticket.voided.
CREATE FUNCTION ticketing.void(p_ticket_id uuid)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog
AS $$
DECLARE
  v_org_id uuid;
BEGIN
  SELECT e.org_id INTO v_org_id
    FROM ticketing.tickets t JOIN events.events e ON e.id = t.event_id
   WHERE t.id = p_ticket_id
     FOR UPDATE OF t;
  IF NOT FOUND
     OR NOT coalesce(app.actor_role() = 'admin'
                     OR (app.actor_role() = 'organizer' AND v_org_id = app.org_id()), false) THEN
    RAISE EXCEPTION 'ticket % is not available to this actor', p_ticket_id
      USING ERRCODE = 'insufficient_privilege';
  END IF;
  UPDATE ticketing.tickets SET status = 'void' WHERE id = p_ticket_id;
END
$$;

GRANT EXECUTE ON FUNCTION ticketing.issue(uuid, uuid, uuid, text, text) TO passripple_api;
GRANT EXECUTE ON FUNCTION ticketing.void(uuid) TO passripple_api;
