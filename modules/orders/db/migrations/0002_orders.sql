-- Orders without accounts. Invariant I5: a sale's fee is frozen at the moment of the sale.
-- An order line records the unit price, fee and fee tax in force when the order was
-- created, and nothing can change them afterwards. This module does not talk to banks:
-- the bank reference of a payment lives in payments (invariant I4).

CREATE TABLE orders.orders (
  id                uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
  event_id          uuid        NOT NULL REFERENCES events.events (id),
  hold_id           uuid        NOT NULL UNIQUE REFERENCES inventory.holds (id),
  -- The buyer has no account: the order keeps a way to reach them.
  contact_email     text        CHECK (contact_email ~ '^[^@[:space:]]+@[^@[:space:]]+$'),
  contact_phone     text        CHECK (contact_phone ~ '^\+?[0-9]{8,15}$'),
  -- SHA-256 of the wallet's access token. The token itself is never stored.
  access_token_hash bytea       NOT NULL UNIQUE CHECK (length(access_token_hash) = 32),
  -- Code the buyer writes in the payment description.
  pay_code          text        NOT NULL UNIQUE CHECK (pay_code ~ '^[0-9A-Z]{4,16}$'),
  amount_crc        integer     NOT NULL CHECK (amount_crc >= 0),
  status            text        NOT NULL DEFAULT 'pending'
                    CHECK (status IN ('pending', 'paid', 'expired', 'refund_due', 'refunded')),
  -- Generated by the browser, so a double click or a retry never creates two orders.
  idem_key          text        NOT NULL UNIQUE CHECK (length(idem_key) BETWEEN 8 AND 128),
  expires_at        timestamptz NOT NULL,
  created_at        timestamptz NOT NULL DEFAULT now(),
  paid_at           timestamptz,
  CHECK (contact_email IS NOT NULL OR contact_phone IS NOT NULL),
  CHECK (status <> 'paid' OR paid_at IS NOT NULL)
);
CREATE INDEX orders_event_idx ON orders.orders (event_id);
CREATE INDEX orders_pending_expiry_idx ON orders.orders (expires_at) WHERE status = 'pending';

CREATE TABLE orders.order_items (
  id               uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
  order_id         uuid        NOT NULL REFERENCES orders.orders (id),
  ticket_type_id   uuid        NOT NULL REFERENCES catalog.ticket_types (id),
  quantity         integer     NOT NULL CHECK (quantity > 0),
  -- Frozen at the moment of the sale (invariant I5), in whole colones per ticket.
  unit_price_crc   integer     NOT NULL CHECK (unit_price_crc >= 0),
  unit_fee_crc     integer     NOT NULL CHECK (unit_fee_crc >= 0),
  unit_fee_tax_crc integer     NOT NULL CHECK (unit_fee_tax_crc >= 0),
  -- Which fee schedule produced the fee, so the figure can be explained later.
  fee_rule         text        NOT NULL CHECK (btrim(fee_rule) <> ''),
  created_at       timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX order_items_order_idx ON orders.order_items (order_id);

-- I5: order lines are append-only. No role, the owner included, can change or remove one.
CREATE TRIGGER order_items_append_only BEFORE UPDATE OR DELETE ON orders.order_items
  FOR EACH ROW EXECUTE FUNCTION app.reject_mutation();
CREATE TRIGGER order_items_no_truncate BEFORE TRUNCATE ON orders.order_items
  FOR EACH STATEMENT EXECUTE FUNCTION app.reject_mutation();

-- An order is never deleted, and only its status moves, along these transitions:
--   pending → paid | expired | refund_due      expired → refund_due
--   paid → refund_due                          refund_due → refunded
CREATE FUNCTION orders.guard_order_update()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = pg_catalog
AS $$
BEGIN
  IF (NEW.id, NEW.event_id, NEW.hold_id, NEW.contact_email, NEW.contact_phone,
      NEW.access_token_hash, NEW.pay_code, NEW.amount_crc, NEW.idem_key, NEW.expires_at,
      NEW.created_at)
     IS DISTINCT FROM
     (OLD.id, OLD.event_id, OLD.hold_id, OLD.contact_email, OLD.contact_phone,
      OLD.access_token_hash, OLD.pay_code, OLD.amount_crc, OLD.idem_key, OLD.expires_at,
      OLD.created_at) THEN
    RAISE EXCEPTION 'order %: only its status can change', OLD.id USING ERRCODE = 'restrict_violation';
  END IF;
  IF NEW.status IS DISTINCT FROM OLD.status
     AND (OLD.status, NEW.status) NOT IN (('pending', 'paid'), ('pending', 'expired'),
                                          ('pending', 'refund_due'), ('expired', 'refund_due'),
                                          ('paid', 'refund_due'), ('refund_due', 'refunded')) THEN
    RAISE EXCEPTION 'order %: % cannot become %', OLD.id, OLD.status, NEW.status
      USING ERRCODE = 'restrict_violation';
  END IF;
  IF OLD.paid_at IS NOT NULL AND NEW.paid_at IS DISTINCT FROM OLD.paid_at THEN
    RAISE EXCEPTION 'order %: the payment time cannot change', OLD.id USING ERRCODE = 'restrict_violation';
  END IF;
  RETURN NEW;
END
$$;

CREATE TRIGGER orders_guard_update BEFORE UPDATE ON orders.orders
  FOR EACH ROW EXECUTE FUNCTION orders.guard_order_update();
CREATE TRIGGER orders_no_delete BEFORE DELETE ON orders.orders
  FOR EACH ROW EXECUTE FUNCTION app.reject_mutation();
CREATE TRIGGER orders_no_truncate BEFORE TRUNCATE ON orders.orders
  FOR EACH STATEMENT EXECUTE FUNCTION app.reject_mutation();

-- ── Row Level Security ───────────────────────────────────────────────────────
-- The API never writes these tables. Organizers see the orders of their organization's
-- events; buyers reach their own order only through orders.order_for_token.
ALTER TABLE orders.orders      ENABLE ROW LEVEL SECURITY, FORCE ROW LEVEL SECURITY;
ALTER TABLE orders.order_items ENABLE ROW LEVEL SECURITY, FORCE ROW LEVEL SECURITY;

CREATE POLICY orders_module_read ON orders.orders FOR SELECT USING (app.is_module_role());
CREATE POLICY orders_module_write ON orders.orders TO passripple_owner_orders
  USING (true) WITH CHECK (true);
CREATE POLICY order_items_module_read ON orders.order_items FOR SELECT USING (app.is_module_role());
CREATE POLICY order_items_module_write ON orders.order_items TO passripple_owner_orders
  USING (true) WITH CHECK (true);

CREATE POLICY orders_api_read ON orders.orders FOR SELECT TO passripple_api
  USING ((SELECT app.actor_role()) = 'admin' OR EXISTS (
    SELECT 1 FROM events.events e
     WHERE e.id = orders.event_id
       AND (SELECT app.actor_role()) = 'organizer' AND e.org_id = (SELECT app.org_id())));
CREATE POLICY order_items_api_read ON orders.order_items FOR SELECT TO passripple_api
  USING (EXISTS (SELECT 1 FROM orders.orders o WHERE o.id = order_items.order_id));

GRANT USAGE ON SCHEMA orders TO passripple_api;
GRANT SELECT ON orders.orders, orders.order_items TO passripple_api;

-- ── Functions ────────────────────────────────────────────────────────────────
-- Creates the order for an active hold and freezes its price and fee (I5). The fee is
-- calculated by the API with the pricing package and passed in; the price is read from
-- the catalog now. Repeating the same idempotency key for the same hold returns the
-- same order.
CREATE FUNCTION orders.create(
  p_hold_id uuid,
  p_idem_key text,
  p_contact_email text,
  p_contact_phone text,
  p_access_token text,
  p_pay_code text,
  p_unit_fee_crc integer,
  p_unit_fee_tax_crc integer,
  p_fee_rule text
) RETURNS uuid
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog
AS $$
DECLARE
  v_existing orders.orders;
  v_hold     inventory.holds;
  v_price    integer;
  v_order_id uuid;
BEGIN
  IF NOT coalesce(app.actor_role() IN ('buyer', 'system'), false) THEN
    RAISE EXCEPTION 'this actor cannot create orders' USING ERRCODE = 'insufficient_privilege';
  END IF;

  SELECT * INTO v_existing FROM orders.orders WHERE idem_key = p_idem_key;
  IF FOUND THEN
    IF v_existing.hold_id = p_hold_id THEN
      RETURN v_existing.id;
    END IF;
    RAISE EXCEPTION 'idempotency key already used for another hold' USING ERRCODE = 'unique_violation';
  END IF;

  IF p_access_token IS NULL OR length(p_access_token) < 32 THEN
    RAISE EXCEPTION 'the access token must have at least 32 characters' USING ERRCODE = 'invalid_parameter_value';
  END IF;

  SELECT * INTO v_hold FROM inventory.holds WHERE id = p_hold_id;
  IF NOT FOUND OR v_hold.ended_at IS NOT NULL OR v_hold.expires_at <= now() THEN
    RAISE EXCEPTION 'hold % is not active', p_hold_id USING ERRCODE = 'object_not_in_prerequisite_state';
  END IF;
  SELECT t.price_crc INTO v_price FROM catalog.ticket_types t WHERE t.id = v_hold.ticket_type_id;

  INSERT INTO orders.orders (event_id, hold_id, contact_email, contact_phone, access_token_hash,
                             pay_code, amount_crc, idem_key, expires_at)
  VALUES (v_hold.event_id, p_hold_id, p_contact_email, p_contact_phone,
          sha256(convert_to(p_access_token, 'UTF8')), p_pay_code,
          v_hold.quantity * (v_price + p_unit_fee_crc + p_unit_fee_tax_crc),
          p_idem_key, v_hold.expires_at)
  ON CONFLICT (idem_key) DO NOTHING
  RETURNING id INTO v_order_id;

  IF v_order_id IS NULL THEN
    -- A concurrent request with the same key won the race.
    SELECT * INTO v_existing FROM orders.orders WHERE idem_key = p_idem_key;
    IF v_existing.hold_id = p_hold_id THEN
      RETURN v_existing.id;
    END IF;
    RAISE EXCEPTION 'idempotency key already used for another hold' USING ERRCODE = 'unique_violation';
  END IF;

  INSERT INTO orders.order_items (order_id, ticket_type_id, quantity, unit_price_crc,
                                  unit_fee_crc, unit_fee_tax_crc, fee_rule)
  VALUES (v_order_id, v_hold.ticket_type_id, v_hold.quantity, v_price,
          p_unit_fee_crc, p_unit_fee_tax_crc, p_fee_rule);
  RETURN v_order_id;
END
$$;

-- Records that an order was paid. Called by payments once per confirmed payment; the API
-- cannot call it. A pending order whose hold is still active becomes paid and its hold
-- becomes issued capacity. A payment that arrives too late leaves the order refund_due.
-- Returns the resulting status, or already_paid.
CREATE FUNCTION orders.mark_paid(p_order_id uuid)
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog
AS $$
DECLARE
  v_order orders.orders;
BEGIN
  SELECT * INTO v_order FROM orders.orders WHERE id = p_order_id FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'order % not found', p_order_id USING ERRCODE = 'no_data_found';
  END IF;
  IF v_order.status = 'paid' THEN
    RETURN 'already_paid';
  END IF;
  IF v_order.status = 'pending' AND inventory.convert_hold(v_order.hold_id) THEN
    UPDATE orders.orders SET status = 'paid', paid_at = now() WHERE id = p_order_id;
    RETURN 'paid';
  END IF;
  IF v_order.status IN ('pending', 'expired') THEN
    UPDATE orders.orders SET status = 'refund_due' WHERE id = p_order_id;
  END IF;
  RETURN 'refund_due';
END
$$;

-- Expires every pending order whose time is up and releases its hold. Run on a schedule.
-- Returns how many orders expired.
CREATE FUNCTION orders.expire_orders(p_now timestamptz DEFAULT now())
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog
AS $$
DECLARE
  v_order orders.orders;
  v_count integer := 0;
BEGIN
  IF app.actor_role() IS DISTINCT FROM 'system' THEN
    RAISE EXCEPTION 'only the system expires orders' USING ERRCODE = 'insufficient_privilege';
  END IF;
  FOR v_order IN
    SELECT * FROM orders.orders
     WHERE status = 'pending' AND expires_at <= p_now
       FOR UPDATE SKIP LOCKED
  LOOP
    UPDATE orders.orders SET status = 'expired' WHERE id = v_order.id;
    PERFORM inventory.release_hold(v_order.hold_id);
    v_count := v_count + 1;
  END LOOP;
  RETURN v_count;
END
$$;

-- The buyer's wallet: the access token reaches exactly one order, and nothing else.
CREATE FUNCTION orders.order_for_token(p_access_token text)
RETURNS TABLE (id uuid, event_id uuid, status text, amount_crc integer, pay_code text,
               expires_at timestamptz, paid_at timestamptz)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = pg_catalog
AS $$
  SELECT o.id, o.event_id, o.status, o.amount_crc, o.pay_code, o.expires_at, o.paid_at
    FROM orders.orders o
   WHERE o.access_token_hash = sha256(convert_to(p_access_token, 'UTF8'));
$$;

GRANT EXECUTE ON FUNCTION orders.create(uuid, text, text, text, text, text, integer, integer, text)
  TO passripple_api;
GRANT EXECUTE ON FUNCTION orders.expire_orders(timestamptz) TO passripple_api;
GRANT EXECUTE ON FUNCTION orders.order_for_token(text) TO passripple_api;
